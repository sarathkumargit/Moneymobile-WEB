import { KeyRound, Smartphone } from "lucide-react";
import { createClient } from "@/lib/supabase/server";
import { Badge } from "@/components/ui/badge";
import { DataTable, ShopFilter, Toolbar, muted } from "@/components/super-admin/parts";
import { LIMIT, loadShops, shopParam } from "@/lib/admin/platform";
import { formatSL } from "@/lib/shared/srilanka-time";

export const dynamic = "force-dynamic";
type Req = { id: string; status: string; created_at: string; imei: string | null; model: string | null; customer_name: string | null; reason: string | null; shop_id: string | null };
type Key = { id: string; status: string; expires_at: string | null; created_at: string; shop_id: string | null; devices: { brand: string | null; model: string | null; imei1: string | null } | null };
const sBadge: Record<string, "success" | "warning" | "danger" | "neutral"> = { pending: "warning", approved: "success", rejected: "danger", active: "success", used: "neutral", expired: "neutral" };

// Read-only overview. Approving requests and generating codes is done by each shop.
export default async function UnlocksPage({ searchParams }: { searchParams: { shop?: string } }) {
  const supabase = createClient();
  const shop = shopParam(searchParams.shop);
  const { list, names } = await loadShops();
  let rq = supabase.from("device_unlock_requests").select("id,status,created_at,imei,model,customer_name,reason,shop_id").order("created_at", { ascending: false }).limit(LIMIT);
  let kq = supabase.from("temporary_unlock_keys").select("id,status,expires_at,created_at,shop_id, devices(brand,model,imei1)").order("created_at", { ascending: false }).limit(LIMIT);
  if (shop) { rq = rq.eq("shop_id", shop); kq = kq.eq("shop_id", shop); }
  const [{ data: reqs }, { data: keys }] = await Promise.all([rq, kq]);
  const requests = (reqs ?? []) as Req[];
  const codes = (keys ?? []) as unknown as Key[];
  const pending = requests.filter((r) => r.status === "pending").length;

  return (
    <>
      <Toolbar title="Customer unlock requests" hint={pending ? `${pending} waiting for the shop` : "Raised by customers from their phone"}><ShopFilter shops={list} current={shop} path="/super-admin/unlocks" /></Toolbar>
      <DataTable icon={Smartphone} emptyTitle="No unlock requests"
        cols={[{ label: "Requested" }, { label: "Customer" }, { label: "Phone" }, { label: "Shop" }, { label: "Reason" }, { label: "Status" }]}
        rows={requests.map((r) => [
          muted(formatSL(r.created_at)),
          <span key="n" className="font-medium">{r.customer_name ?? "—"}</span>,
          muted([r.model, r.imei].filter(Boolean).join(" · ") || null),
          r.shop_id ? names[r.shop_id] ?? "—" : "—",
          muted(r.reason),
          <Badge key="s" variant={sBadge[r.status] ?? "neutral"} className="capitalize">{r.status}</Badge>,
        ])} />

      <Toolbar title="Temporary unlock codes" hint="Generated by shops for phones that are offline" />
      <DataTable icon={KeyRound} emptyTitle="No unlock codes generated"
        cols={[{ label: "Created" }, { label: "Phone" }, { label: "Shop" }, { label: "Expires" }, { label: "Status" }]}
        rows={codes.map((k) => [
          muted(formatSL(k.created_at)),
          <span key="p" className="font-medium">{[k.devices?.brand, k.devices?.model, k.devices?.imei1].filter(Boolean).join(" · ") || "—"}</span>,
          k.shop_id ? names[k.shop_id] ?? "—" : "—",
          muted(k.expires_at ? formatSL(k.expires_at) : null),
          <Badge key="s" variant={sBadge[k.status] ?? "neutral"} className="capitalize">{k.status}</Badge>,
        ])} />
    </>
  );
}
